// Rebuilds art-source/requests/INDEX.md: one row per request with its status,
// engine, accepted variant and plan.
// Usage, from the repository root: bun tools/images/index.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { requestsDir } from "./src/paths";

const rows: string[] = [];
const counts: Record<string, number> = {};
for (const file of readdirSync(requestsDir).filter((name) => /^IMG-\d{4}-.*\.md$/.test(name)).sort()) {
  const text = readFileSync(join(requestsDir, file), "utf8");
  const heading = /^# (IMG-\d{4}) — (.+)$/m.exec(text);
  const status = /^status:\s*(\S+)/m.exec(text)?.[1] ?? "?";
  const plan = /^plan:\s*(\S+)/m.exec(text)?.[1] ?? "?";
  const model = /"model":\s*"([^"]+)"/.exec(text)?.[1] ?? "?";
  const accepted = [...text.matchAll(/\*\*accepted: (v\d+)\*\*/g)].pop()?.[1] ?? "";
  counts[status] = (counts[status] ?? 0) + 1;
  rows.push(`| [${heading?.[1]}](${file}) | ${heading?.[2]} | ${status} | ${accepted} | ${model.startsWith("codex/") ? "Sol" : "gateway"} | ${plan} |`);
}
const summary = Object.entries(counts).map(([status, count]) => `${count} ${status}`).join(", ");
writeFileSync(
  join(requestsDir, "INDEX.md"),
  `# Image requests\n\nGenerated by \`bun tools/images/index.ts\`; don't edit by hand. ${rows.length} requests: ${summary}.\n\n| ID | Title | Status | Accepted | Engine | Plan |\n|---|---|---|---|---|---|\n${rows.join("\n")}\n`,
);
console.log(`${rows.length} requests: ${summary}`);
